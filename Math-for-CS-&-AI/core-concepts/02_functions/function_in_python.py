def greet_user(name):
    print(f" Hi, {name}")
    print("Welcome")


print("Start")
greet_user("Nibras")
greet_user("Mohamed")
print("Finish")

#Multiple parameters
def names(first_name, last_name):
    print(f" Hi, {first_name} {last_name}")
    print("Welcome")


print("Start")
names("Mohamed", "Nibras")
print("Finish")

